"""DecBush1-lvl5 -- the Decorative Bush at level 5.

Level 4 (decbush1_lvl4.build) with the topiary gilded (details.recolor); the clipped hedge round
it stays green. Models only -- the game stops at level 3 for now. Generated by gen_lvl5.py.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import details as d  # noqa: E402
import detail  # noqa: E402,F401
import kit  # noqa: E402

OBJ = "DecBush1-lvl5"
L4 = kit.borrow("decbush1_lvl4.py")
LVL5_DX = L4['LVL4_DX'] * 4 / 3


def build(lo, hi):
    b = L4['build'](lo, hi)
    d.recolor(b, {'leaf': 'gold', 'grass_dark': 'gold', 'grass': 'gold'},
              where=lambda c: c.z > 0.3 and abs(c.x) < 0.3 and abs(c.y) < 0.3)
    return b


kit.run(OBJ, build, source_name="DecBush1-lvl1", offset=(LVL5_DX, 0, 0),
        collection="Развлечения")
