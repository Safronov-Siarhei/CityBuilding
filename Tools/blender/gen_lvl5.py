"""Writes <id>1_lvl5.py next to every <id>1_lvl4.py (or only the stems given). Level 5 is the
same for every building -- level 4 with its roofs gilded (details.gild_roofs) -- so the scripts
differ only in names, and each is still a plain kit.borrow of level 4. Plain python, not Blender:

    python gen_lvl5.py .                  (from Tools/blender; all of them)
    python gen_lvl5.py . hovel1 cottage1  (only these)
"""
import glob
import os
import re
import sys

OUT = sys.argv[1]
ONLY = sys.argv[2:]

TEMPLATE = '''"""{obj}-lvl5 -- the {en} at level 5: the golden roof.

Level 4 ({stem}_lvl4.build) with every roof slope gilded (details.gild_roofs): the tiles turn
gold under the dark lattice, while the verges, ridge rolls and walls keep their colours. Level
4 was colour with gold diamonds; level 5 is gold with dark ones. Models only -- the game stops
at level 3 for now. Generated by gen_lvl5.py.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import details as d  # noqa: E402
import detail  # noqa: E402
import kit  # noqa: E402

OBJ = "{obj}-lvl5"
L4 = kit.borrow("{stem}_lvl4.py")
LVL5_DX = L4['LVL4_DX'] * 4 / 3
detail.OVERRIDE['gold'] = detail.TILES   # gold reads as tiles on a slope (this model only)


def build(lo, hi):
    b = L4['build'](lo, hi)
    d.gild_roofs(b)
    return b


kit.run(OBJ, build, source_name="{obj}-lvl1", offset=(LVL5_DX, 0, 0),
        collection="{coll}")
'''

n = 0
for path in sorted(glob.glob(os.path.join(OUT, "*_lvl4.py"))):
    stem = os.path.basename(path)[:-len("_lvl4.py")]
    if ONLY and stem not in ONLY:
        continue
    src = open(path, encoding="utf-8").read()
    obj = re.search(r'^OBJ = "(.+)-lvl4"', src, re.M).group(1)
    coll = re.search(r'collection="([^"]+)"', src).group(1)
    en = re.search(r'-lvl4 -- the (.+?) \(', src).group(1)
    with open(os.path.join(OUT, stem + "_lvl5.py"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(TEMPLATE.format(obj=obj, en=en, stem=stem, coll=coll))
    n += 1
print(n, "written")
