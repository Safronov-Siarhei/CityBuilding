"""Writes <id>1_lvl5.py next to every <id>1_lvl4.py (or only the stems given). Level 5 is level 4
with its roofs gilded (details.gild_roofs); SPECIAL below lists the buildings that differ -- Food,
whose straw-yellow thatch would swallow gold, and the ones with no roof to gild. Each script is
still a plain kit.borrow of level 4. Plain python, not Blender:

    python gen_lvl5.py .                  (from Tools/blender; all of them)
    python gen_lvl5.py . hovel1 cottage1  (only these)
"""
import glob
import os
import re
import sys
import textwrap

OUT = sys.argv[1]
ONLY = sys.argv[2:]

GILD = ("every roof slope gilded (details.gild_roofs): the tiles turn gold under the dark "
        "lattice, while the verges, ridge rolls and walls keep their colours. Level 4 was colour "
        "with gold diamonds; level 5 is gold with dark ones.")
FOOD = ("every roof slope re-laid in red-orange glazed tiles (details.gild_roofs with "
        "color='roof_orange'): Food's thatch is straw-yellow already and would swallow gold, so "
        "its level 5 is red-orange tile under the dark lattice.")

# stem -> (what level 5 does, build body lines, draw gold as tiles?)
SPECIAL = {s: (FOOD, "d.gild_roofs(b, color='roof_orange')", False)
           for s in ("orchard1", "fisherhut1", "pigfarm1", "smokehouse1", "windmill1", "baker1")}
SPECIAL.update({
    "farm1": ("the wheat ripened to gold (every ear in the field gilded) and the rail fence round "
              "the field painted in Food's level-5 red-orange (details.recolor) -- the wheat alone "
              "was yellow already, so the fence is what reads.",
              "d.recolor(b, {'hay': 'gold', 'roof_straw': 'gold'},\n"
              "          where=lambda c: abs(c.x) < 0.45 and c.y > -0.38 and c.z > 0.05)\n"
              "d.recolor(b, {'wood_mid': 'roof_orange', 'wood_dark': 'roof_red'},\n"
              "          where=lambda c: (abs(c.x) > 0.43 or abs(c.y) > 0.43) and c.z > 0.05)",
              False),
    "townsquare1": ("the fountain cast in gold: its basin, column and bowls gilded "
                    "(details.recolor); the water and the paving keep their colours.",
                    "d.recolor(b, {'stone_light': 'gold', 'stone_mid': 'gold'},\n"
                    "          where=lambda c: c.x * c.x + c.y * c.y < 0.55 ** 2 and c.z > 0.04)",
                    False),
    "flag1": ("the banner turned to cloth of gold with a violet emblem -- its colours swapped "
              "(details.recolor).",
              "d.recolor(b, {'roof_purple': 'gold', 'gold': 'roof_purple'},\n"
              "          where=lambda c: c.z > 1.2 and c.x > 0.03 and abs(c.y) < 0.08)", False),
    "dectree1": ("the crown turned to gold leaf (details.recolor); the trunk, planter and "
                 "lanterns keep their colours.",
                 "d.recolor(b, {'leaf': 'gold', 'grass_dark': 'gold'}, where=lambda c: c.z > 0.6)",
                 False),
    "decbush1": ("the topiary gilded (details.recolor); the clipped hedge round it stays green.",
                 "d.recolor(b, {'leaf': 'gold', 'grass_dark': 'gold', 'grass': 'gold'},\n"
                 "          where=lambda c: c.z > 0.3 and abs(c.x) < 0.3 and abs(c.y) < 0.3)",
                 False),
    "decgarden1": ("the fountain and the two clipped cones at the path's ends gilded "
                   "(details.recolor).",
                   "d.recolor(b, {'stone_light': 'gold', 'stone_mid': 'gold'},\n"
                   "          where=lambda c: abs(c.x) < 0.2 and abs(c.y) < 0.2 and c.z > 0.035)\n"
                   "d.recolor(b, {'leaf': 'gold'},\n"
                   "          where=lambda c: 1.15 < abs(c.x) < 1.35 and abs(c.y) < 0.1)",
                   False),
})

TEMPLATE = '''"""{obj}-lvl5 -- the {en} at level 5.

{doc}
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import details as d  # noqa: E402
import detail  # noqa: E402,F401
import kit  # noqa: E402

OBJ = "{obj}-lvl5"
L4 = kit.borrow("{stem}_lvl4.py")
LVL5_DX = L4['LVL4_DX'] * 4 / 3
{override}

def build(lo, hi):
    b = L4['build'](lo, hi)
{body}
    return b


kit.run(OBJ, build, source_name="{obj}-lvl1", offset=(LVL5_DX, 0, 0),
        collection="{coll}")
'''

n = 0
for path in sorted(glob.glob(os.path.join(OUT, "*1_lvl4.py"))):   # model scripts, not gen_lvl4.py
    stem = os.path.basename(path)[:-len("_lvl4.py")]
    if ONLY and stem not in ONLY:
        continue
    src = open(path, encoding="utf-8").read()
    obj = re.search(r'^OBJ = "(.+)-lvl4"', src, re.M).group(1)
    coll = re.search(r'collection="([^"]+)"', src).group(1)
    en = re.search(r'-lvl4 -- the (.+?) \(', src).group(1)
    what, body, tiles = SPECIAL.get(stem, (GILD, "d.gild_roofs(b)", True))
    doc = "\n".join(textwrap.wrap(f"Level 4 ({stem}_lvl4.build) with {what} Models only -- the "
                                  "game stops at level 3 for now. Generated by gen_lvl5.py.", 96,
                                  break_on_hyphens=False))
    override = ("detail.OVERRIDE['gold'] = detail.TILES   # gold reads as tiles on a slope "
                "(this model only)\n" if tiles else "")
    with open(os.path.join(OUT, stem + "_lvl5.py"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(TEMPLATE.format(obj=obj, en=en, stem=stem, coll=coll, doc=doc, override=override,
                                 body=textwrap.indent(body, "    ")))
    n += 1
print(n, "written")
