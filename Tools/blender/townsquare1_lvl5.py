"""TownSquare1-lvl5 -- the Town Square at level 5.

Level 4 (townsquare1_lvl4.build) with the fountain cast in gold: its basin, column and bowls
gilded (details.recolor); the water and the paving keep their colours. Models only -- the game
stops at level 3 for now. Generated by gen_lvl5.py.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import details as d  # noqa: E402
import detail  # noqa: E402,F401
import kit  # noqa: E402

OBJ = "TownSquare1-lvl5"
L4 = kit.borrow("townsquare1_lvl4.py")
LVL5_DX = L4['LVL4_DX'] * 4 / 3


def build(lo, hi):
    b = L4['build'](lo, hi)
    d.recolor(b, {'stone_light': 'gold', 'stone_mid': 'gold'},
              where=lambda c: c.x * c.x + c.y * c.y < 0.55 ** 2 and c.z > 0.04)
    return b


kit.run(OBJ, build, source_name="TownSquare1-lvl1", offset=(LVL5_DX, 0, 0),
        collection="Развлечения")
