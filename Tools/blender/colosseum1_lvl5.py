"""Colosseum1-lvl5 -- the Colosseum at level 5.

Level 4 (colosseum1_lvl4.build) with every roof slope gilded (details.gild_roofs): the tiles
turn gold under the dark lattice, while the verges, ridge rolls and walls keep their colours.
Level 4 was colour with gold diamonds; level 5 is gold with dark ones. Models only -- the game
stops at level 3 for now. Generated by gen_lvl5.py.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import details as d  # noqa: E402
import detail  # noqa: E402,F401
import kit  # noqa: E402

OBJ = "Colosseum1-lvl5"
L4 = kit.borrow("colosseum1_lvl4.py")
LVL5_DX = L4['LVL4_DX'] * 4 / 3
detail.OVERRIDE['gold'] = detail.TILES   # gold reads as tiles on a slope (this model only)


def build(lo, hi):
    b = L4['build'](lo, hi)
    d.gild_roofs(b)
    return b


kit.run(OBJ, build, source_name="Colosseum1-lvl1", offset=(LVL5_DX, 0, 0),
        collection="Развлечения")
