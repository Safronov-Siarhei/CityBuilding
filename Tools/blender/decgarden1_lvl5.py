"""DecGarden1-lvl5 -- the Decorative Garden at level 5.

Level 4 (decgarden1_lvl4.build) with the fountain and the two clipped cones at the path's ends
gilded (details.recolor). Models only -- the game stops at level 3 for now. Generated by
gen_lvl5.py.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import details as d  # noqa: E402
import detail  # noqa: E402,F401
import kit  # noqa: E402

OBJ = "DecGarden1-lvl5"
L4 = kit.borrow("decgarden1_lvl4.py")
LVL5_DX = L4['LVL4_DX'] * 4 / 3


def build(lo, hi):
    b = L4['build'](lo, hi)
    d.recolor(b, {'stone_light': 'gold', 'stone_mid': 'gold'},
              where=lambda c: abs(c.x) < 0.2 and abs(c.y) < 0.2 and c.z > 0.035)
    d.recolor(b, {'leaf': 'gold'},
              where=lambda c: 1.15 < abs(c.x) < 1.35 and abs(c.y) < 0.1)
    return b


kit.run(OBJ, build, source_name="DecGarden1-lvl1", offset=(LVL5_DX, 0, 0),
        collection="Развлечения")
