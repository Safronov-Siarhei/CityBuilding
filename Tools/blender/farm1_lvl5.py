"""Farm1-lvl5 -- the Farm at level 5.

Level 4 (farm1_lvl4.build) with the wheat ripened to gold (every ear in the field gilded) and
the rail fence round the field painted in Food's level-5 red-orange (details.recolor) -- the
wheat alone was yellow already, so the fence is what reads. Models only -- the game stops at
level 3 for now. Generated by gen_lvl5.py.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import details as d  # noqa: E402
import detail  # noqa: E402,F401
import kit  # noqa: E402

OBJ = "Farm1-lvl5"
L4 = kit.borrow("farm1_lvl4.py")
LVL5_DX = L4['LVL4_DX'] * 4 / 3


def build(lo, hi):
    b = L4['build'](lo, hi)
    d.recolor(b, {'hay': 'gold', 'roof_straw': 'gold'},
              where=lambda c: abs(c.x) < 0.45 and c.y > -0.38 and c.z > 0.05)
    d.recolor(b, {'wood_mid': 'roof_orange', 'wood_dark': 'roof_red'},
              where=lambda c: (abs(c.x) > 0.43 or abs(c.y) > 0.43) and c.z > 0.05)
    return b


kit.run(OBJ, build, source_name="Farm1-lvl1", offset=(LVL5_DX, 0, 0),
        collection="Производство еды")
