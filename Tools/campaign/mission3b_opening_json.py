"""Writes Assets/_Project/Campaign/Mission3Opening.json: mission 3b «Клетка»'s opening scene (the forest ambush,
storyboard v3 and all four animation groups approved by the user 2026-11-23) laid out for CityDefenceMode.Escort.cs
(Capital.cs's film machinery, far from the map). Run it AFTER Tools/blender/cinematic/export_m3opening.py: the
cameras are the approved review cameras, read per frame from Campaign/M3Opening/<group>.json (`cam`).

The four takes follow one another on the scene's own clock: the column 0-17, the ambush 17-26, the fight 26-38,
the King 38-53.3; each is shown from its start to the next one's.
"""
import json
import math
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
TAKES = os.path.join(ROOT, "Assets", "_Project", "Campaign", "M3Opening")
OUT = os.path.join(ROOT, "Assets", "_Project", "Campaign", "Mission3Opening.json")
GROUPS = ("column", "ambush", "melee", "rally")

# The cart's four wheels, from the cart's own track (cage_cart.py: hubs at (+-WHEEL_X, WHEEL_YS, WHEEL_R) x SCALE,
# rolling with the distance): the export took them from cc.make(), which hands back ONE object per name -- the front
# pair stood on the back pair's spot and the takes' wheel tracks were wrong. Unity frame: Blender (x, y, z) -> (x, z, y),
# a turn about x reversed.
CART_SCALE = 1.6 * 0.55
WHEEL_R = 0.2 * CART_SCALE
HUBS = [(sx * (0.36 + 0.03) * CART_SCALE, WHEEL_R, wy * CART_SCALE) for wy in (-0.5 + 0.16, 0.5 - 0.16) for sx in (-1, 1)]


def qmul(a, b):
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return (aw * bx + ax * bw + ay * bz - az * by, aw * by - ax * bz + ay * bw + az * bx,
            aw * bz + ax * by - ay * bx + az * bw, aw * bw - ax * bx - ay * by - az * bz)


def qrot(q, v):
    x, y, z, w = qmul(qmul(q, (v[0], v[1], v[2], 0.0)), (-q[0], -q[1], -q[2], q[3]))
    return (x, y, z)


def fix_wheels(take):
    cart = next((p for p in take["props"] if p["piece"] == "CapPropM3CageCartBare"), None)
    if cart is None:
        return
    m = cart["m"]
    n = len(m) // 7
    tracks = [[] for _ in HUBS]
    dist = 0.0
    for f in range(n):
        px, py, pz, qx, qy, qz, qw = m[f * 7:f * 7 + 7]
        if f:
            dist += math.dist((px, py, pz), m[(f - 1) * 7:(f - 1) * 7 + 3])
        roll = dist / WHEEL_R
        spin = (-math.sin(roll / 2), 0.0, 0.0, math.cos(roll / 2))
        q = qmul((qx, qy, qz, qw), spin)
        for k, hub in enumerate(HUBS):
            o = qrot((qx, qy, qz, qw), hub)
            tracks[k] += [round(px + o[0], 4), round(py + o[1], 4), round(pz + o[2], 4),
                          round(q[0], 5), round(q[1], 5), round(q[2], 5), round(q[3], 5)]
    take["props"] = [p for p in take["props"] if "Wheel" not in p["piece"]]
    for k, t in enumerate(tracks):
        take["props"].append({"piece": "CapPropM3CageWheel" + ("L" if HUBS[k][0] < 0 else "R"), "m": t})


uses, shots = [], []
end = 0.0
for g in GROUPS:
    with open(os.path.join(TAKES, g + ".json"), encoding="utf-8") as f:
        take = json.load(f)
    fix_wheels(take)
    with open(os.path.join(TAKES, g + ".json"), "w", encoding="utf-8") as f:
        json.dump(take, f, ensure_ascii=False, separators=(",", ":"))
    t0 = float(take.get("start", 0.0))
    t1 = t0 + float(take["seconds"])
    end = max(end, t1)
    uses.append({"group": g, "place": "road", "origin": [0, 0, 0], "turn": 0, "start": t0, "show": [t0, t1]})
    shots.append({"place": "road", "t0": t0, "t1": t1, "path": take["cam"], "pathFps": take["fps"]})
shots[-1]["t1"] = end + 1.0


def line(t, seconds, who, key):
    return {"t": t, "seconds": seconds, "who": who, "key": key}


# column_anim HAND, ambush_anim SHOUT, rally_anim RALLY / SAY1 / SAY2
lines = [
    line(13.0, 2.8, "#cine_name_horseman", "#cine_m3_halt"),
    line(17.6, 2.0, "#cine_name_king", "#cine_m3_ambush"),
    line(39.6, 1.6, "#cine_name_king", "#cine_m3_follow"),
    line(48.2, 1.8, "#cine_name_king", "#cine_m3_for_him"),
    line(50.6, 2.6, "#cine_name_king", "#cine_m3_clear"),
]

script = {
    "_about": "GENERATED by Tools/campaign/mission3b_opening_json.py -- edit there. Mission 3b's opening scene "
              "(CityDefenceMode.Escort.cs; export Tools/blender/cinematic/export_m3opening.py). One far place, the "
              "forest road set; each shot's `path` is the approved review camera per frame (Blender frame).",
    "places": [{"name": "road", "set": "M3RoadSet", "at": [-1500, 0, 1500]}],
    "uses": uses,
    "shots": shots,
    "lines": lines,
    "end": round(end, 2), "fadeIn": 0.6, "fade": 1.0, "subFadeIn": 0.25, "subFadeOut": 0.35,
    # the ride's music, the fight's from the horn (ambush_anim HORN 17.2)
    "musicVolume": 0.5, "music2At": 17.0, "musicCross": 1.0, "musicFadeOut": 2.0,
}
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    json.dump(script, f, ensure_ascii=False, indent=1)
print("ok", len(uses), "uses", len(shots), "shots, end", round(end, 2))
